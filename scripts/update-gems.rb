#!/usr/bin/env ruby
# Update every gem to the newest version released at least COOLDOWN_DAYS ago
# (default 14), then pin all of them — direct and transitive — exactly in
# Gemfile.pins.
#
# Usage: scripts/update-gems.rb        (run with Homebrew Ruby, see serve.sh)
#        COOLDOWN_DAYS=30 scripts/update-gems.rb
#
# How it works: resolve with no pins, look up each locked version's release
# date on rubygems.org, cap any too-new gem at its newest eligible release,
# and re-resolve until nothing violates the cooldown.

require "bundler"
require "json"
require "net/http"
require "time"

Dir.chdir(File.expand_path("..", __dir__))

COOLDOWN_DAYS = Integer(ENV.fetch("COOLDOWN_DAYS", "14"))
CUTOFF = Time.now - COOLDOWN_DAYS * 24 * 60 * 60
PINS_FILE = "Gemfile.pins"
HEADER = "# Generated by scripts/update-gems.rb -- do not edit by hand.\n" \
         "# Every version was released on or before %s (%d-day cooldown).\n"

def versions(name)
  @versions ||= {}
  @versions[name] ||= begin
    res = Net::HTTP.get_response(URI("https://rubygems.org/api/v1/versions/#{name}.json"))
    abort "rubygems.org lookup failed for #{name}: HTTP #{res.code}" unless res.is_a?(Net::HTTPSuccess)
    JSON.parse(res.body)
  end
end

def released_at(name, number, platform)
  match = versions(name).find { |v| v["number"] == number && v["platform"] == platform } ||
          versions(name).find { |v| v["number"] == number }
  abort "#{name} #{number} not found on rubygems.org" unless match
  Time.parse(match["created_at"])
end

def newest_eligible(name)
  eligible = versions(name).reject { |v| v["prerelease"] }
                           .select { |v| Time.parse(v["created_at"]) <= CUTOFF }
  abort "#{name} has no release older than #{COOLDOWN_DAYS} days" if eligible.empty?
  eligible.map { |v| Gem::Version.new(v["number"]) }.max.to_s
end

def write_pins(pins)
  body = pins.sort.map { |name, req| "#{name} #{req}\n" }.join
  File.write(PINS_FILE, format(HEADER, CUTOFF.utc.strftime("%Y-%m-%d"), COOLDOWN_DAYS) + body)
end

# Bundler lists a gem once per platform; every platform must pass the cooldown.
def locked_specs
  Bundler::LockfileParser.new(File.read("Gemfile.lock")).specs
                         .reject { |s| s.name == "bundler" }
end

def run(*cmd)
  system(*cmd) or abort "failed: #{cmd.join(' ')}"
end

puts "Cooldown cutoff: #{CUTOFF.utc.strftime('%Y-%m-%d %H:%M UTC')}"

caps = {}
loop do
  write_pins(caps.transform_values { |v| "<= #{v}" })
  File.delete("Gemfile.lock") if File.exist?("Gemfile.lock")
  run("bundle", "lock")

  too_new = locked_specs.select do |spec|
    released_at(spec.name, spec.version.to_s, spec.platform.to_s) > CUTOFF
  end
  break if too_new.empty?

  too_new.uniq(&:name).each do |spec|
    cap = newest_eligible(spec.name)
    puts "  #{spec.name} #{spec.version} is too new -> capping at #{cap}"
    abort "could not resolve #{spec.name} within the cooldown" if caps[spec.name] == cap
    caps[spec.name] = cap
  end
end

specs = locked_specs.uniq(&:name)
write_pins(specs.to_h { |s| [s.name, "= #{s.version}"] })
File.delete("Gemfile.lock")
run("bundle", "lock")
run("bundle", "install", "--quiet")

puts "Pinned #{specs.size} gems:"
specs.sort_by(&:name).each do |s|
  puts format("  %-28s %-12s released %s", s.name, s.version,
              released_at(s.name, s.version.to_s, s.platform.to_s).strftime("%Y-%m-%d"))
end
